using System;

namespace Lab01_Debugging
{
    class Program
    {
        // Метод вычисления квадрата числа 
        static int Sqr(int x)                                    //  10
        {                                                        //  11
            int q = x * x;                                       //  12  — вычисляем квадрат
            return q;                                            //  13  — возвращаем результат
        }                                                        //  14

        // Метод подсчёта суммы элементов массива 
        static int Sum(int[] x, int N)                           //  1
        {                                                        //  2
            int s = 0;                                           //  3  — инициализация суммы
            for (int i = 0; i < N; i++)                          //  4  — цикл по всем элементам
                s += x[i];                                       //  5  — прибавляем текущий элемент
            return s;                                            //  6  — возвращаем сумму
        }                                                        //  7

        // Метод ввода целого числа с клавиатуры
        static int ReadInt(string prompt)                        //  8
        {                                                        //  9
            Console.Write(prompt);                               //  10 — выводим приглашение
            int x = int.Parse(Console.ReadLine());               //  11 — читаем и преобразуем ввод
            return x;                                            //  12 — возвращаем число
        }                                                        //  13

        static void Main(string[] args)                          //  14
        {                                                        //  15
         
            const int N = 10;                                    //  16  — размер массива
            int[] a = { 5, 2, 7, -9, 4, 8, -1, 0, 3, 6 };        //  17  — исходный массив

            // Находим сумму квадратов положительных элементов
            int s = 0;                                           //  18  — инициализация суммы
            for (int i = 0; i < N; i++)                          //  19  — цикл от 0 до 9
            {                                                    //  20
                if (a[i] > 0)                                    //  21  — проверка: элемент положительный?
                    s += Sqr(a[i]);                              //  22  — если да — добавляем квадрат
            }                                                    //  23

            Console.WriteLine($"Массив a: [{string.Join(", ", a)}]");
            Console.WriteLine($"Сумма квадратов положительных: {s}\n");  // ожидаем 203


            int[] b = new int[N] { 1, 3, -5, 0, 4, 6, -1, 9, 3, 2 }; //  24  — новый массив

            // 1. Поиск максимального элемента
            int m = b[0];                                        // строка 25  — пока максимум = первый элемент
            for (int i = 1; i < N; i++)                          // строка 26  — цикл с 1-го индекса
            {                                                    // строка 27
                if (m < b[i])                                    // строка 28  — если нашли больше
                    m = b[i];                                    // строка 29  — обновляем максимум
            }                                                    // строка 30
            Console.WriteLine($"Массив b: [{string.Join(", ", b)}]");
            Console.WriteLine($"Максимум m = {m}");              // ожидаем m = 9

            // 2. Сумма элементов массива через метод Sum
            int sum = Sum(b, N);                                 //  31  — вызов метода Sum
            Console.WriteLine($"Сумма элементов s = {sum}");     // ожидаем s = 22

            // 3. Вычисление z и k
            int z = sum / m;                                     //  32  — целочисленное деление 22/9 = 2
            int k = 0;                                           //  33  — инициализация k

            for (int i = 0; i < N; i++)                          //  34  — цикл по массиву
            {                                                    // 35
                if (b[i] > z)                                    //  36  — ← СЮДА СТАВИМ ТОЧКУ ОСТАНОВА
                    k += b[i];                                   //  37  — элемент больше z → прибавляем
                else                                             //  38
                    k -= b[i];                                   //  39  — иначе вычитаем
            }                                                    //  40
            Console.WriteLine($"z = {z}, k = {k}\n");            // ожидаем z=2, k=28

            // 4. Цикл while с вводом пользователя
            //    (сюда тоже ставятся условные точки останова)
            Console.WriteLine("Введите два числа (x и y):");
            int x = ReadInt("x = ");                             //  41
            int y = ReadInt("y = ");                             //  42

            int result = 0;                                      //  43
            while ((x != 0) && (y != 0))                         //  44  — ← УСЛОВНАЯ ТОЧКА ОСТАНОВА
            {                                                    //  45
                x--;                                             //  46  — уменьшаем x
                y--;                                             //  47  — уменьшаем y
                result += x + y;                                 //  48  — накапливаем сумму
            }                                                    //  49

            Console.WriteLine($"Результат цикла while = {result}");
        }                                                        
    }
}
